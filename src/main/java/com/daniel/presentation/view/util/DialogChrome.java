package com.daniel.presentation.view.util;

import javafx.scene.Node;
import javafx.application.Platform;
import javafx.scene.Scene;
import javafx.scene.control.Dialog;
import javafx.scene.paint.Color;
import javafx.stage.StageStyle;
import javafx.stage.Window;

/**
 * Removes the OS titlebar from any Dialog and enables transparent premium card styling.
 * Call {@link #apply(Dialog, Node)} in the dialog constructor, before show().
 */
public final class DialogChrome {

    private DialogChrome() {}

    /** Default cap used when no screen can be measured (headless tests). */
    static final double FALLBACK_SCREEN_HEIGHT = 720;

    /** Supplies the application window the dialogs belong to (null = none known). */
    private static java.util.function.Supplier<Window> ownerSupplier;

    public static void ownerSupplier(java.util.function.Supplier<Window> supplier) {
        ownerSupplier = supplier;
    }

    /**
     * Pure choice of the usable height: the screen whose visual bounds contain the owner's centre
     * (else one intersecting it), else the first screen, else the fallback. Tested with explicit
     * rectangles; the native owner is only an input.
     */
    static double usableHeight(javafx.geometry.Rectangle2D owner, java.util.List<javafx.geometry.Rectangle2D> screens, double fallback) {
        return usableBounds(owner, screens, new javafx.geometry.Rectangle2D(0, 0, 1280, fallback)).getHeight();
    }

    private static javafx.geometry.Rectangle2D usableBounds(javafx.geometry.Rectangle2D owner,
            java.util.List<javafx.geometry.Rectangle2D> screens, javafx.geometry.Rectangle2D fallback) {
        if (screens == null || screens.isEmpty()) return fallback;
        if (owner != null) {
            double cx = owner.getMinX() + owner.getWidth() / 2, cy = owner.getMinY() + owner.getHeight() / 2;
            for (javafx.geometry.Rectangle2D s : screens) if (s.contains(cx, cy)) return s;
            for (javafx.geometry.Rectangle2D s : screens) if (s.intersects(owner)) return s;
        }
        return screens.get(0);
    }

    /** The window the dialog should follow: its explicit owner, else the application window. */
    private static Window ownerOf(Dialog<?> dialog) {
        Window owner = dialog.getOwner();
        if (owner == null && ownerSupplier != null) owner = ownerSupplier.get();
        return owner;
    }

    /** Entrance/exit of every framed dialog through the central Motion (cancellable, reduce-motion aware). */
    static void animate(Dialog<?> dialog) {
        Node pane = dialog.getDialogPane();
        boolean[] active = {false}, shown = {false}, closing = {false}, committing = {false};
        // Capture both native input and actions generated by accelerators/Button.fire().
        // Disabling the whole pane here would abruptly apply :disabled opacity before the fade.
        pane.addEventFilter(javafx.scene.input.InputEvent.ANY, e -> { if (closing[0]) e.consume(); });
        pane.addEventFilter(javafx.event.ActionEvent.ACTION, e -> { if (closing[0]) e.consume(); });
        dialog.addEventHandler(javafx.scene.control.DialogEvent.DIALOG_SHOWN, e -> {
            active[0] = shown[0] = true;
            Motion.dialogIn(pane, Motion.PANEL_MS);
        });
        // ANY is deliberately after handlers for CLOSE_REQUEST, including the caller's veto.
        // No animation may start for a request consumed by a busy filter or handler.
        dialog.addEventHandler(javafx.scene.control.DialogEvent.ANY, e -> {
            if (e.getEventType() != javafx.scene.control.DialogEvent.DIALOG_CLOSE_REQUEST || e.isConsumed()) return;
            if (shown[0] && !active[0]) { e.consume(); return; } // setResult() followed by close()
            if (committing[0] || !dialog.isShowing()) return;
            if (closing[0]) { e.consume(); return; }
            if (Motion.reduced()) return;
            e.consume();
            closing[0] = true;

            Motion.dialogOut(pane, Motion.PANEL_MS, () -> {
                if (!active[0]) return;
                pane.setOpacity(0); // keep it hidden until close(), never flash at the final pulse
                Platform.runLater(() -> {
                    if (!active[0] || !closing[0]) return;
                    committing[0] = true;
                    try { dialog.close(); }
                    finally {
                        committing[0] = false;
                        // A caller can still veto the final close. Restore a usable dialog.
                        if (dialog.isShowing()) {
                            closing[0] = false;

                            Motion.settle(pane);
                        }
                    }
                });
            });
        });
        dialog.addEventHandler(javafx.scene.control.DialogEvent.DIALOG_HIDDEN, e -> {
            active[0] = false;

            closing[0] = false;
            Motion.settle(pane);
        });
    }

    /**
     * The shared dialog frame: a header row (title + close button, also the drag handle) and a
     * body that scrolls on its own. The dialog's own ButtonBar stays outside the scroll, so
     * Confirm/Cancel remain reachable however short the window is.
     *
     * @param closeAllowed asked when the user presses the header's close button (false while a
     *                     write is in flight, so the dialog stays until it answers)
     * @return the scroll pane that hosts {@code body} (for callers that need to re-fit it)
     */
    public static javafx.scene.control.ScrollPane frame(Dialog<?> dialog, String title, Node body,
                                                        java.util.function.BooleanSupplier closeAllowed) {
        javafx.scene.control.Label titleLabel = new javafx.scene.control.Label(title);
        titleLabel.getStyleClass().add("dialog-title-label");
        titleLabel.setWrapText(true);
        javafx.scene.control.Button closeBtn = new javafx.scene.control.Button(null, Icons.close());
        closeBtn.getStyleClass().addAll("icon-btn", "dialog-close-btn");
        closeBtn.setTooltip(new javafx.scene.control.Tooltip("Fechar (Esc)"));
        closeBtn.setAccessibleText("Fechar");
        closeBtn.setOnAction(e -> { if (closeAllowed == null || closeAllowed.getAsBoolean()) dialog.close(); });
        javafx.scene.layout.Region spacer = new javafx.scene.layout.Region();
        javafx.scene.layout.HBox.setHgrow(spacer, javafx.scene.layout.Priority.ALWAYS);
        javafx.scene.layout.HBox.setHgrow(titleLabel, javafx.scene.layout.Priority.ALWAYS);
        javafx.scene.layout.HBox headerRow = new javafx.scene.layout.HBox(titleLabel, spacer, closeBtn);
        headerRow.getStyleClass().add("dialog-header-row");
        apply(dialog, headerRow);

        javafx.scene.control.ScrollPane scroll = new javafx.scene.control.ScrollPane(body);
        scroll.getStyleClass().add("dialog-body-scroll");
        scroll.setFitToWidth(true);
        scroll.setMinSize(0, 0);
        scroll.setHbarPolicy(javafx.scene.control.ScrollPane.ScrollBarPolicy.NEVER);
        scroll.setVbarPolicy(javafx.scene.control.ScrollPane.ScrollBarPolicy.AS_NEEDED);
        javafx.scene.layout.VBox.setVgrow(scroll, javafx.scene.layout.Priority.ALWAYS);
        javafx.scene.layout.VBox content = new javafx.scene.layout.VBox(0, headerRow, scroll);
        content.setMinSize(0, 0);
        dialog.getDialogPane().setContent(content);

        // Dialogs open over the application window (centred on it, capped by ITS screen).
        if (dialog.getOwner() == null && ownerSupplier != null) {
            Window app = ownerSupplier.get();
            try { if (app != null) dialog.initOwner(app); } catch (IllegalStateException alreadyShown) { /* keep */ }
        }
        // Cap the height by the screen the dialog will open on, so the button bar stays on screen.
        // addEventHandler, not setOnShowing: a caller's own setOnShowing must not silently drop the cap.
        dialog.addEventHandler(javafx.scene.control.DialogEvent.DIALOG_SHOWING, e -> {
            Scene sc = dialog.getDialogPane().getScene();
            if (sc != null) sc.setFill(Color.TRANSPARENT);
            fitToScreen(dialog);
        });
        dialog.addEventHandler(javafx.scene.control.DialogEvent.DIALOG_SHOWN, e -> Platform.runLater(() -> fitToScreen(dialog)));
        animate(dialog);
        return scroll;
    }

    private static javafx.geometry.Rectangle2D usableScreenBounds(Dialog<?> dialog) {
        javafx.geometry.Rectangle2D fallback = new javafx.geometry.Rectangle2D(0, 0, 1280, FALLBACK_SCREEN_HEIGHT);
        try {
            Window owner = ownerOf(dialog);
            javafx.geometry.Rectangle2D rect = owner == null || !Double.isFinite(owner.getX()) ? null
                    : new javafx.geometry.Rectangle2D(owner.getX(), owner.getY(), Math.max(1, owner.getWidth()), Math.max(1, owner.getHeight()));
            java.util.List<javafx.geometry.Rectangle2D> screens = javafx.stage.Screen.getScreens().stream()
                    .map(javafx.stage.Screen::getVisualBounds).toList();
            return usableBounds(rect, screens, fallback);
        } catch (RuntimeException e) {
            return fallback;
        }
    }

    private static void fitToScreen(Dialog<?> dialog) {
        var bounds = usableScreenBounds(dialog);
        var pane = dialog.getDialogPane();
        double width = Math.max(240, bounds.getWidth() - 48);
        double[] declared = (double[]) pane.getProperties().computeIfAbsent(DialogChrome.class.getName() + ".declaredWidth",
                key -> new double[]{pane.getMinWidth(), pane.getPrefWidth()});
        pane.setMinHeight(0);
        pane.setMaxWidth(width);
        pane.setMinWidth(Math.min(Math.max(0, declared[0]), width));
        pane.setPrefWidth(Math.min(Math.max(declared[0], declared[1] > 0 ? declared[1] : 440), width));
        capHeight(pane, bounds.getHeight());
        if (!dialog.isShowing()) return;
        pane.applyCss();
        pane.layout();
        pane.getScene().getWindow().sizeToScene();
        dialog.setWidth(Math.min(dialog.getWidth(), width));
        dialog.setHeight(Math.min(dialog.getHeight(), pane.getMaxHeight()));
        dialog.setX(Math.max(bounds.getMinX(), Math.min(dialog.getX(), bounds.getMaxX() - dialog.getWidth())));
        dialog.setY(Math.max(bounds.getMinY(), Math.min(dialog.getY(), bounds.getMaxY() - dialog.getHeight())));
    }

    /**
     * Limits the dialog pane to {@code screenHeight} minus a margin; the body scroll inside the
     * frame yields first (its max height follows), the header and the button bar never shrink.
     */
    public static void capHeight(javafx.scene.control.DialogPane pane, double screenHeight) {
        double cap = Math.max(240, screenHeight - 48);
        pane.setMaxHeight(cap);
        Node content = pane.getContent();
        if (content != null) {
            Node scroll = content.lookup(".dialog-body-scroll");
            if (scroll instanceof javafx.scene.control.ScrollPane sp) {
                // header ≈ 52, button bar ≈ 64 incl. paddings/borders
                sp.setMaxHeight(Math.max(120, cap - 52 - 64 - 8));
            }
        }
        if (pane.getPrefHeight() > cap) pane.setPrefHeight(javafx.scene.layout.Region.USE_COMPUTED_SIZE);
        if (pane.getMinHeight() > cap) pane.setMinHeight(javafx.scene.layout.Region.USE_COMPUTED_SIZE);
    }

    /** Refit after inline validation adds content, keeping the action bar reachable. */
    public static void resizeToContent(Dialog<?> dialog) {
        Platform.runLater(() -> {
            if (!dialog.isShowing()) return;
            fitToScreen(dialog);
        });
    }

    /**
     * @param dialog     the dialog to decorate
     * @param dragHandle node the user can drag to reposition the dialog window
     */
    public static void apply(Dialog<?> dialog, Node dragHandle) {
        try {
            dialog.initStyle(StageStyle.TRANSPARENT);
        } catch (IllegalStateException alreadyShown) {
            // style can only be set before the first show; keep the current one
        }

        // Make the scene background transparent when the dialog opens (composable: never setOnShowing)
        dialog.addEventHandler(javafx.scene.control.DialogEvent.DIALOG_SHOWING, e -> {
            Scene sc = dialog.getDialogPane().getScene();
            if (sc != null) sc.setFill(Color.TRANSPARENT);
        });

        // Drag-to-move: capture origin on press, move window on drag
        double[] origin = {0, 0};
        dragHandle.setOnMousePressed(ev -> {
            Scene sc = dialog.getDialogPane().getScene();
            if (sc == null) return;
            Window w = sc.getWindow();
            if (w != null) {
                origin[0] = ev.getScreenX() - w.getX();
                origin[1] = ev.getScreenY() - w.getY();
            }
        });
        dragHandle.setOnMouseDragged(ev -> {
            Scene sc = dialog.getDialogPane().getScene();
            if (sc == null) return;
            Window w = sc.getWindow();
            if (w != null) {
                w.setX(ev.getScreenX() - origin[0]);
                w.setY(ev.getScreenY() - origin[1]);
            }
        });
    }
}
